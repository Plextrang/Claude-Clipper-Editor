"""Integration: build remotion/src/data/scenes.ts + work/plan/video.json from the scene files, swap generic
monospace for DM Mono, and strip any remaining backdrop-filter usage.

Scenes are auto-discovered: remotion/src/scenes/FS*.tsx = full-screen, OS*.tsx = on-screen (over the talking head).
Each scene file must export <ID>_FROM and <ID>_TO (absolute frames). Full-screen scenes should also export
<ID>_OPAQUE_FROM / <ID>_OPAQUE_UNTIL (frames where the scene fully covers the A-roll; the render skips decoding it).
Opacity fallbacks: work/plan/scene_reports.json, then a workflow journal passed via env SCENE_JOURNAL.
video.json is the single per-video timing source for build_cues.py, mix.py, strips.py and qa_sheets.py."""
import venv_boot  # noqa: F401  (re-runs this script inside .venv when it exists)
import os, re, json, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RM = os.path.join(os.path.dirname(ROOT), 'remotion')
J = os.environ.get('SCENE_JOURNAL', '')


def discover():
    ids = [os.path.basename(p)[:-4] for p in glob.glob(os.path.join(RM, 'src', 'scenes', '*.tsx'))]
    full = sorted([i for i in ids if i.startswith('FS')], key=lambda i: file_range(i)[0])
    over = sorted([i for i in ids if i.startswith('OS')], key=lambda i: file_range(i)[0])
    return full, over


def latest_reports():
    lab, res = {}, {}
    if not J or not os.path.exists(J):
        return res
    for l in open(J, encoding='utf-8'):
        d = json.loads(l)
        if d['type'] == 'started':
            lab[d['key']] = d['label']
        elif d['type'] == 'result' and d.get('result'):
            L = lab.get(d['key'], '')
            kind, _, sid = L.partition(':')
            if kind in ('impl', 'fix'):
                # fix results supersede impl results
                if kind == 'fix' or sid not in res or res[sid][0] != 'fix':
                    res[sid] = (kind, d['result'])
    return res


def file_range(sid):
    src = open(os.path.join(RM, 'src', 'scenes', sid + '.tsx'), encoding='utf-8').read()
    ma = re.search(sid + r'_FROM\s*=\s*(\d+)', src)
    mb = re.search(sid + r'_TO\s*=\s*(\d+)', src)
    assert ma and mb, f'{sid}: export {sid}_FROM / {sid}_TO as plain integer literals (no type annotation, no expression)'
    return int(ma.group(1)), int(mb.group(1))


def file_opaque(sid):
    src = open(os.path.join(RM, 'src', 'scenes', sid + '.tsx'), encoding='utf-8').read()
    of = re.search(sid + r'_OPAQUE_FROM\s*=\s*(-?\d+)', src)
    ou = re.search(sid + r'_OPAQUE_UNTIL\s*=\s*(-?\d+)', src)
    return (int(of.group(1)) if of else None), (int(ou.group(1)) if ou else None)


def patch_files():
    n_mono = n_bd = 0
    skip = [x for x in os.environ.get('SKIP', '').split(',') if x]
    for p in glob.glob(os.path.join(RM, 'src', 'scenes', '*.tsx')):
        if any(k in p for k in skip):
            continue
        s = open(p, encoding='utf-8').read()
        o = s
        # generic monospace -> DM Mono (keep generic fallback); exact tokens only
        s = s.replace("'monospace'", "\"'DM Mono', monospace\"").replace('"monospace"', "\"'DM Mono', monospace\"")
        s = re.sub(r"const MONO\s*=\s*([\"'])(?:(?!\1).)*monospace\1", "const MONO = \"'DM Mono', monospace\"", s)
        s = re.sub(r"const MONO\s*=\s*loadJetBrainsMono\([^)]*\)\.fontFamily", "const MONO = \"'DM Mono', monospace\"", s)
        if s != o:
            n_mono += 1
        # strip backdrop-filter properties (JS style objects and CSS strings)
        s2 = re.sub(r"\n\s*(?:WebkitBackdropFilter|backdropFilter)\s*:\s*[^,\n]+,?", "", s)
        if s2 != s:
            n_bd += 1
        s = s2
        if s != o:
            open(p, 'w', encoding='utf-8', newline='\n').write(s)
    print('patched mono in', n_mono, 'files; removed backdrop-filter in', n_bd, 'files')


def main():
    import sys
    if "--no-patch" not in sys.argv:
        patch_files()
    FULL, OVER = discover()
    reps = latest_reports()
    rp = os.path.join(ROOT, 'plan', 'scene_reports.json')
    saved = json.load(open(rp, encoding='utf-8')) if os.path.exists(rp) else {}
    edl = json.load(open(os.path.join(ROOT, 'transcript', 'edl.json')))
    total = int(edl['total_frames'])
    lines = ["import {FSDef, OSDef} from './types';"]
    for sid in FULL + OVER:
        lines.append(f"import {{{sid}}} from '../scenes/{sid}';")
    lines.append('')
    lines.append('// Generated by work/scripts/integrate.py — every scene owns its own transitions (mounted with plain cuts).')
    lines.append(f'export const TOTAL_FRAMES = {total};')
    lines.append('export const FULLSCREEN: FSDef[] = [')
    vfs, vos = [], []
    for sid in FULL:
        a, b = file_range(sid)
        of, ou = file_opaque(sid)
        if of is None:
            r = reps.get(sid, (None, None))[1] or saved.get(sid) or {}
            of, ou = r.get('opaqueFrom', -1), r.get('opaqueUntil', -1)
        if of is None or of < a or of >= b:
            of = b  # unknown -> never skip A-roll
        if ou is None or ou <= of or ou > b:
            ou = of
        lines.append(f"  {{id: '{sid}', from: {a}, to: {b}, Comp: {sid}, opaqueFrom: {of}, opaqueUntil: {ou}}},")
        vfs.append({'id': sid, 'from': a, 'to': b, 'opaqueFrom': of, 'opaqueUntil': ou})
    lines.append('];')
    lines.append('export const ONSCREEN: OSDef[] = [')
    for sid in OVER:
        a, b = file_range(sid)
        lines.append(f"  {{id: '{sid}', from: {a}, to: {b}, Comp: {sid}}},")
        vos.append({'id': sid, 'from': a, 'to': b})
    lines.append('];')
    open(os.path.join(RM, 'src', 'data', 'scenes.ts'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    # per-video timing source for the python side (cues, mix, QA strips)
    ed = open(os.path.join(RM, 'src', 'data', 'edit.ts'), encoding='utf-8').read()
    jumps = [int(x['out_in_f']) for x in edl['edl'][1:]]  # every EDL piece boundary is a jump cut
    cam_cuts = [int(x) for x in re.findall(r"\{f:\s*(\d+)[^}]*ease:\s*'cut'", ed)]
    pts = {0, total - 1, *jumps, *cam_cuts}
    for x in vfs + vos:
        pts.update([x['from'], x['to']])
    video = {'fps': int(edl.get('fps', 30)), 'total': total, 'fullscreen': vfs, 'onscreen': vos, 'jumpCuts': jumps,
             'points': sorted(p for p in pts if 0 <= p < total)}
    json.dump(video, open(os.path.join(ROOT, 'plan', 'video.json'), 'w'), indent=1)
    if reps:  # refresh saved reports only when a journal was actually read
        saved.update({k: v[1] for k, v in reps.items()})
        json.dump(saved, open(rp, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)


if __name__ == '__main__':
    main()
